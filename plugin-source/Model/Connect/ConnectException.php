<?php
/**
 * Failure of the one-click connection, with the reason shown to the merchant.
 */
declare(strict_types=1);

namespace Skydropx\Shipping\Model\Connect;

use Magento\Framework\Phrase;
use Skydropx\Shipping\Model\Build;

/**
 * Carries a reason code (never a secret, code, state or token) and maps it to the merchant message.
 */
class ConnectException extends \RuntimeException
{
    // Preflight and callback (HU §6.4.1, §6.4.2).
    public const NOT_BUILT = 'not_built';
    public const INVALID_STORE_URL = 'invalid_store_url';
    public const ORIGIN_MISMATCH = 'origin_mismatch';
    public const BEARER_REQUIRED = 'bearer_required';
    public const STATE_INVALID = 'state_invalid';
    public const CODE_INVALID = 'code_invalid';
    public const INTEGRATION_FAILED = 'integration_failed';

    // Exchange answers (contract §4.4, HU §6.4.4).
    public const INVALID_REQUEST = 'invalid_request';
    public const TOKEN_REJECTED = 'token_rejected';
    public const UNAVAILABLE = 'unavailable';
    public const STORE_TAKEN = 'store_taken';
    public const CODE_GONE = 'code_gone';
    public const RATE_LIMITED = 'rate_limited';
    public const SIGNING_UNAVAILABLE = 'signing_unavailable';
    public const UNREACHABLE = 'unreachable';
    public const INVALID_RESPONSE = 'invalid_response';

    /**
     * @param string $reason One of the constants above.
     * @param int|null $httpStatus Status of the exchange, when there was one.
     * @param string|null $detail JSON:API detail or transport message, for the log only.
     */
    public function __construct(
        private string $reason,
        private ?int $httpStatus = null,
        private ?string $detail = null
    ) {
        parent::__construct($reason);
    }

    /**
     * Reason code.
     *
     * @return string
     */
    public function getReason(): string
    {
        return $this->reason;
    }

    /**
     * HTTP status of the exchange (0 = no answer), or null when eco was not called.
     *
     * @return int|null
     */
    public function getHttpStatus(): ?int
    {
        return $this->httpStatus;
    }

    /**
     * Error detail for the log.
     *
     * @return string|null
     */
    public function getDetail(): ?string
    {
        return $this->detail;
    }

    /**
     * Message for the merchant. Plain text: the message manager escapes it.
     *
     * @return Phrase
     */
    public function getMerchantMessage(): Phrase
    {
        $brand = Build::NAME;

        switch ($this->reason) {
            case self::NOT_BUILT:
                return __(
                    'This module is not built: the service URLs are missing. Install a package generated by the build.'
                );
            case self::INVALID_STORE_URL:
                return __(
                    'The store URL cannot be connected: it must be an https address with a public domain name '
                    . '(no IP address, localhost or internal domain).'
                );
            case self::ORIGIN_MISMATCH:
                return __(
                    'The Magento admin runs on a different domain or port than the store, so the one-click connection '
                    . 'is not possible. Connect manually: in %1 › My stores › your store › Settings › Extension, copy '
                    . 'the store ID and generate the signing key, then paste both in this section and save.',
                    $brand
                );
            case self::BEARER_REQUIRED:
                return __(
                    'Check "Allow integration tokens as Bearer (required to connect)" and click Connect again.'
                );
            case self::STATE_INVALID:
                return __('The link expired; click Connect again.');
            case self::CODE_INVALID:
                return __('The connection code is not valid. Click Connect again.');
            case self::INTEGRATION_FAILED:
                return __('We could not create the Magento integration for %1. Try again.', $brand);
            case self::TOKEN_REJECTED:
                return __(
                    'Magento rejected the integration token. Check that "Allow OAuth Access Tokens to be used as '
                    . 'standalone Bearer tokens" is enabled and connect again.'
                );
            case self::UNAVAILABLE:
                return __(
                    'The one-click connection is not available for your account. Use the manual connection or '
                    . 'contact %1 support.',
                    $brand
                );
            case self::STORE_TAKEN:
                return __(
                    'This store is already connected to another %1 account. Disconnect it there in My stores and '
                    . 'try again.',
                    $brand
                );
            case self::CODE_GONE:
                return __('The connection code expired or was already used. Click Connect again.');
            case self::RATE_LIMITED:
                return __('Too many attempts. Wait a minute and try again.');
            case self::SIGNING_UNAVAILABLE:
                return __('%1 cannot connect stores right now. Try again later.', $brand);
            case self::UNREACHABLE:
                return __('We could not reach %1. Try again later.', $brand);
            case self::INVALID_RESPONSE:
                return __('%1 sent an unexpected answer. Try again later.', $brand);
            case self::INVALID_REQUEST:
            default:
                return __('We could not connect the store because of a module error. Contact %1 support.', $brand);
        }
    }
}
